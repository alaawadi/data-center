  var lang = 'ar';

  function overrides() {
    var st = window.Store ? Store.state : null;
    if (!st) return {};
    st.i18nOverrides = st.i18nOverrides || { ar: {}, en: {} };
    st.i18nOverrides[lang] = st.i18nOverrides[lang] || {};
    return st.i18nOverrides[lang];
  }

  function base(key) {
    return (DICT[lang] && DICT[lang][key]) || (DICT.ar[key]) || key;
  }

  function t(key, vars) {
    var text = overrides()[key];
    if (text == null || text === '') text = base(key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        text = String(text).split('{{' + k + '}}').join(vars[k]);
      });
    }
    return text;
  }

  function setOverride(key, value) {
    var o = overrides();
    if (value == null || value === '' || value === DICT[lang][key]) delete o[key];
    else o[key] = value;
    if (window.Store) Store.save(true);
    apply();
    document.dispatchEvent(new CustomEvent('i18n:change'));
  }

  function resetAll() {
    var st = Store.state;
    st.i18nOverrides[lang] = {};
    Store.save(true);
    apply();
    document.dispatchEvent(new CustomEvent('i18n:change'));
  }

  function keys() {
    var seen = {};
    var out = [];
    Object.keys(DICT.ar).forEach(function (k) { seen[k] = 1; out.push(k); });
    Object.keys(DICT.en).forEach(function (k) { if (!seen[k]) { seen[k] = 1; out.push(k); } });
    return out;
  }

  function original(key) { return DICT.ar[key] || key; }
  function otherLang(key) { return DICT.en[key] || key; }

  function apply() {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-label]').forEach(function (el) {
      var l = el.querySelector('.sr-only');
      if (l) l.textContent = t(el.getAttribute('data-i18n-label'));
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-label')));
    });
  }

  function setLang(next) {
    lang = next === 'en' ? 'en' : 'ar';
    if (window.Store) {
      Store.state.ui = Store.state.ui || {};
      Store.state.ui.lang = lang;
      Store.save(true);
    }
    apply();
    document.dispatchEvent(new CustomEvent('i18n:change'));
  }

  function init() {
    var st = window.Store ? Store.init() : null;
    if (st && st.ui && st.ui.lang) lang = st.ui.lang === 'en' ? 'en' : 'ar';
    apply();
    return lang;
  }

  window.I18n = {
    init: init,
    t: t,
    setLang: setLang,
    getLang: function () { return lang; },
    apply: apply,
    keys: keys,
    base: base,
    original: original,
    otherLang: otherLang,
    setOverride: setOverride,
    resetAll: resetAll,
    overrides: overrides
  };
